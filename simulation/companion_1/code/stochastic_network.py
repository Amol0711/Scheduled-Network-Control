#!/usr/bin/env python3
"""High-power CRN stochastic validation for Stochastic.

This script evaluates the full nonlinear six-node Stuart--Landau network with
20,000 common-random-number paths, explicitly includes the analytical modal cap
optimum, uses a dense local cap grid, forms paired and family-wise confidence
intervals, estimates a fixed-design quadratic vertex, and performs a nested
Euler--Maruyama step-halving check.

The calculation is resumable.  Use ``--reset`` once, then invoke repeatedly
with ``--chunk-paths`` until the final summary is produced.  Brownian increments
are generated by a fixed NumPy PCG64 stream and are shared across all caps.
"""
